            float roi_h = static_cast<float>(bboxes[bboxBase + BBOX_IDX_H]) * spatial_scale;
            float roi_a = static_cast<float>(bboxes[bboxBase + BBOX_IDX_A]);
            float w_2 = roi_w * HALF_FACTOR;
            float h_2 = roi_h * HALF_FACTOR;
