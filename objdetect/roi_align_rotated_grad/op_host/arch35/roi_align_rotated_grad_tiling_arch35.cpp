static ge::graphStatus ComputeTiling(gert::TilingContext* context, RoiAlignRotatedGradTilingData* tiling,
                                     int64_t coreNum)
{
    auto attrs = context->GetAttrs();
    OP_CHECK_NULL_WITH_CONTEXT(context, attrs);

    // ---- 1. 读取属性（对标 910B 属性索引）----
    auto yGradShape = attrs->GetListInt(kYGradShapeIdx)->GetData();
    int64_t pooledHeight = *(attrs->GetAttrPointer<int64_t>(kPooledHIdx));
    int64_t pooledWidth = *(attrs->GetAttrPointer<int64_t>(kPooledWIdx));
    int64_t samplingRatio = *(attrs->GetAttrPointer<int64_t>(kSamplingRatioIdx));
    float spatialScale = *(attrs->GetAttrPointer<float>(kSpatialScaleIdx));
    bool aligned = *(attrs->GetAttrPointer<bool>(kAlignedIdx));
    bool clockwise = *(attrs->GetAttrPointer<bool>(kClockwiseIdx));

    // ---- 2. roiNum 从 rois shape 元信息获取（无值依赖，SE §6.7）----
    auto roisShapePtr = context->GetInputShape(kRoisIdx);
    OP_CHECK_NULL_WITH_CONTEXT(context, roisShapePtr);
    auto roisShape = roisShapePtr->GetStorageShape();

    tiling->batchSize = yGradShape[BATCH_DIM];
    tiling->height = yGradShape[HEIGHT_DIM];
    tiling->width = yGradShape[WIDTH_DIM];
    tiling->channelNum = yGradShape[CHANNEL_DIM];
    tiling->roiNum = roisShape.GetDim(1);
    tiling->pooledHeight = pooledHeight;
    tiling->pooledWidth = pooledWidth;
    tiling->samplingRatio = samplingRatio;
    tiling->spatialScale = spatialScale;
    tiling->aligned = aligned ? 1 : 0;
    tiling->clockwise = clockwise ? 1 : 0;

    // ---- 3. segsPerRow / totalUnits（MDE §2.1）----
    tiling->segsPerRow = (tiling->channelNum + C_SEG_SIZE - 1) / C_SEG_SIZE; // C=0 → 0
    tiling->totalUnits = tiling->batchSize * tiling->height * tiling->width * tiling->segsPerRow;

    // ---- 4. 核数（MDE §2.1 公式：min(AIV, totalUnits)，下限 1；无 PER_CORE_MIN）----
    tiling->needCoreNum = std::min(coreNum, tiling->totalUnits);
    if (tiling->needCoreNum <= 0) {
        tiling->needCoreNum = 1; // totalUnits == 0（空输出）兜底，VF 循环体不执行
    }
    return ge::GRAPH_SUCCESS;
}

