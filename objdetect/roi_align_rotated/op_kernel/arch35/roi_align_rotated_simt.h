    scaleWord.f = tilingData->spatialScale;
    paramsTensor.SetValue(OFF_POOLED_W, tilingData->pooledW);
    paramsTensor.SetValue(OFF_POOLED_H, tilingData->pooledH);
    paramsTensor.SetValue(OFF_CHANNELS, tilingData->channels);
    paramsTensor.SetValue(OFF_HEIGHT, tilingData->height);
    paramsTensor.SetValue(OFF_WIDTH, tilingData->width);
    paramsTensor.SetValue(OFF_SAMPLING_RATIO, tilingData->samplingRatio);
