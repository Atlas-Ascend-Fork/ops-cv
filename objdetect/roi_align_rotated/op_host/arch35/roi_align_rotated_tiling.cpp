// ========== ComputeTiling（两步法切分）==========
void ComputeTiling(Arch35TilingState& st, RoiAlignRotatedArch35TilingData* tiling)
{
    // totalElements = R × C × pooled_h × pooled_w（int64 防溢出；R=0 时为 0）
    tiling->totalElements = st.roisNum * st.channels * st.pooledH * st.pooledW;
    // Step 1: 按物理核均分得到每核处理量，下限保护 PER_CORE_MIN
    int64_t blockFactor = (tiling->totalElements + st.coreNum - 1) / st.coreNum;
    if (blockFactor < PER_CORE_MIN) {
        blockFactor = PER_CORE_MIN;
    }
    // Step 2: 反推实际核数（R=0 时 totalElements=0 → needCoreNum=0 → 下限保护为 1）
    tiling->needCoreNum = static_cast<int32_t>((tiling->totalElements + blockFactor - 1) / blockFactor);
    if (tiling->needCoreNum > st.coreNum) {
        tiling->needCoreNum = static_cast<int32_t>(st.coreNum);
    }
    if (tiling->needCoreNum <= 0) {
        tiling->needCoreNum = 1; // R=0 空切分 → 单核空转（kernel 侧 Process 早退，静默返回）
    }
    st.needCoreNum = tiling->needCoreNum;
}

