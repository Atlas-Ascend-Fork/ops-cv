void PrintReport(const std::vector<CaseResult>& results)
{
    printf("\n");
    printf("==========================================================================================================="
           "==========\n");
    printf("| %-30s | %-8s | %-9s | %-12s | %-7s | %-8s | %-8s | %-24s\n", "Case", "Build", "RunGraph", "OutputExists",
           "OutCnt", "Expect", "Check", "ErrMsg");
    printf("-----------------------------------------------------------------------------------------------------------"
           "----------\n");
    int pass_cnt = 0;
    int total = results.size();
    for (const auto& r : results) {
        // 正向须校验输出形状与数值；负向须确认具体的 NHWC 格式拒绝原因。
        bool pass = CasePassed(r);
        if (pass)
            pass_cnt++;
        printf("| %-30s | %-8s | %-9s | %-12s | %-7d | %-8s | %-8s | %-24s\n", r.case_name.c_str(),
               r.build_ok ? "OK" : "FAIL", r.run_ok ? "OK" : "FAIL", r.output_exists ? "OK" : "FAIL", r.output_count,
               r.expect_reject ? "REJECT" : "OK", pass ? "OK" : "FAIL", r.err_msg.empty() ? "-" : r.err_msg.c_str());
    }
    printf("==========================================================================================================="
           "==========\n");
    printf("Summary: %d/%d passed\n", pass_cnt, total);
}

int main()
{
    printf("%s - INFO - [XIR]: Start to initialize ge using ge global options\n", GetTime().c_str());
    // 设置全局选项
    std::map<AscendString, AscendString> global_options = {
        {"ge.exec.deviceId", "0"}, {"ge.graphRunMode", "0"}, {"ge.exec.precision_mode", "must_keep_origin_dtype"}};
    // 初始化图引擎
    Status ret = ge::GEInitialize(global_options);
    if (ret != SUCCESS) {
        printf("%s - INFO - [XIR]: Initialize ge using ge global options failed\n", GetTime().c_str());
        return FAILED;
    }
    printf("%s - INFO - [XIR]: Initialize ge using ge global options success\n", GetTime().c_str());

    // dtype 矩阵
    struct DtypeEntry {
        DataType dt;
        std::string name;
    };
    std::vector<DtypeEntry> dtype_list = {
        {DT_FLOAT, "FP32"},
    };

    // shape 场景矩阵：本算子为双输入依赖算子（x 恒 4 维，rois 恒 2 维），每个场景给出一组
    // (x_shape, rois_shape) 合法组合， 保证输出 y=(R,C,pooled_h,pooled_w)
    // 可正常构图运行，本示例中的最大 C 为 1024，最大 R 为 32。
    // 场景裁剪说明：参考模板的标量{1}/1维{64}/8维{2,2,2,2,2,2,2,2}场景对本算子不合法——本算子 rank 固定
    // （x 必须 4 维、rois 必须 2 维），构造标量/1 维/8 维输入会导致构图 infershape 校验失败，故按边界场景
    // 裁剪规则跳过；模板的空tensor场景{0,8}适配为本算子的合法空输入边界 R=0（rois={0,6}，输出 (0,C,7,7) 空tensor）。
    struct ShapeCombo {
        Format xFormat;
        std::vector<int64_t> xShape;
        std::vector<int64_t> roisShape;
        std::string name;
    };
    std::vector<ShapeCombo> shape_list = {
        {FORMAT_NCHW, {1, 16, 8, 8}, {2, 6}, "regular"},         // 基线场景：N=1, C=16, H=W=8, R=2
        {FORMAT_NCHW, {2, 32, 16, 16}, {8, 6}, "regular_batch"}, // 常规多维：N/C/H/W 变化
        {FORMAT_NCHW, {1, 64, 32, 32}, {16, 6}, "multi_rois"},   // RoI 数量增大：R=16
        {FORMAT_NCHW, {4, 8, 32, 64}, {32, 6}, "wide_hw"},       // H/W 拉大：H=32, W=64
        {FORMAT_NCHW, {1, 1024, 4, 4}, {1, 6}, "channel_upper"}, // 通道上界：C=1024
        {FORMAT_NCHW, {1, 16, 8, 8}, {0, 6}, "empty_rois_r0"},   // 空输入边界：R=0，输出 (0,C,7,7)
        {FORMAT_ND, {1, 16, 8, 8}, {2, 6}, "regular_nd"}, // ND 无布局声明：按 NCHW 维度序解释，同 regular
    };

    // 950 上 x format=NHWC 时tiling ValidateFormat 显式拒绝。shape 按 NCHW
    // 构造（x (N,C,H,W)、rois (R,6) 行主序，使 infershape 通过），确保拒绝发生在 tiling 闸门；
    // 预期 RunGraph 失败，且须确认错误包含 NHWC 与 "only supports NCHW and ND"。
    // ND 为无布局声明，950 按 NCHW 维度序正常承接（见 shape_list 的 regular_nd 正向用例）。
    struct RejectCombo {
        Format xFormat;
        std::vector<int64_t> xShape;
        std::vector<int64_t> roisShape;
        std::string name;
    };
    std::vector<RejectCombo> reject_list = {
        {FORMAT_NHWC, {1, 16, 8, 8}, {2, 6}, "nhwc_rejected"}, // NHWC→cv 契约布局（老芯片语义），950 拒绝
    };

    // 动态 shape 泛化用例矩阵（graph desc 显式声明，real 恒具体）：
    //   - 部分 -1（unknown dim，rank 已知）：未知的 N/R/C 透传到输出 y=(R,C,7,7) 对应位置；
    //   - rois 末维未知 {-1,-1}：dim1 不再是常量 6，验证推导/tiling 对 unknown dim 的容忍；
    //   - -2（unknown rank，UNKNOWN_DIM_NUM）：单侧/双侧输入 {-2}，entry infershape
    //     IsUnknownRank → SetUnknownRank(output) 透传（def.cpp DynamicRankSupportFlag=true）。
    // real 组合取 regular 基线（x={1,16,8,8}、rois={2,6}、y={2,16,7,7}=1568 元素）。
    std::vector<DynCombo> dyn_list = {
        // 部分 -1：仅 x 的 N 未知 + rois 的 R 未知
        {{1, 16, 8, 8}, {-1, 16, 8, 8}, {2, 6}, {-1, 6}, {-1, 16, 7, 7}, "dyn_xn_rois_r"},
        // 部分 -1：x 的 N/C 未知（C 透传到 y.dim(1)）
        {{1, 16, 8, 8}, {-1, -1, 8, 8}, {2, 6}, {-1, 6}, {-1, -1, 7, 7}, "dyn_xnc"},
        // x 全 -1（rank 4 已知）+ rois 仅 R 未知（dim1=6 已知）
        {{1, 16, 8, 8}, {-1, -1, -1, -1}, {2, 6}, {-1, 6}, {-1, -1, 7, 7}, "dyn_x_all"},
        // rois 末维未知：rois={-1,-1}，dim1 非常量（推导侧需容忍 -1）
        {{1, 16, 8, 8}, {1, 16, 8, 8}, {2, 6}, {-1, -1}, {2, 16, 7, 7}, "dyn_rois_d1_unknown"},
        // -2 未知 rank：双输入均 unknown rank，输出 unknown rank 透传
        {{1, 16, 8, 8}, {-2}, {2, 6}, {-2}, {-2}, "unknown_rank_both"},
        // -2 未知 rank：仅 x 侧（rois 侧部分 -1）
        {{1, 16, 8, 8}, {-2}, {2, 6}, {-1, 6}, {-2}, "unknown_rank_x"},
        // -2 未知 rank：仅 rois 侧（x 侧部分 -1）
        {{1, 16, 8, 8}, {-1, 16, 8, 8}, {2, 6}, {-2}, {-2}, "unknown_rank_rois"},
    };

    // 单 session 复用
    std::map<AscendString, AscendString> build_options = {};
    ge::Session* session = new Session(build_options);
    if (session == nullptr) {
        printf("%s - ERROR - [XIR]: create session failed\n", GetTime().c_str());
        ge::GEFinalize();
        return FAILED;
    }

    std::vector<CaseResult> results;
    uint32_t graph_id = 0;

    // N_dtype × N_shape × 2 mode 全矩阵（正向：x format=NCHW，950 实现分支）
    for (const auto& d : dtype_list) {
        for (const auto& s : shape_list) {
            for (auto mode : {RUN_MODE_S, RUN_MODE_D}) {
                std::string mode_name = (mode == RUN_MODE_S) ? "S" : "D";
                std::string case_name = d.name + "_" + s.name + "_" + mode_name;
                printf("\n%s - INFO - [XIR]: ===== %s =====\n", GetTime().c_str(), case_name.c_str());
                CaseResult r = RunOneCase(session, graph_id, mode, d.dt, s.xFormat, s.xShape, s.roisShape, case_name,
                                          false);
                results.push_back(r);
                graph_id++;
            }
        }
    }

    // format 路由负向用例（S 模式单档）：NHWC 输入预期被 tiling 显式拒绝
    for (const auto& d : dtype_list) {
        for (const auto& rej : reject_list) {
            std::string case_name = d.name + "_" + rej.name;
            printf("\n%s - INFO - [XIR]: ===== %s (expect tiling reject) =====\n", GetTime().c_str(),
                   case_name.c_str());
            CaseResult r = RunOneCase(session, graph_id, RUN_MODE_S, d.dt, rej.xFormat, rej.xShape, rej.roisShape,
                                      case_name, true);
            results.push_back(r);
            graph_id++;
        }
    }

    // 动态 shape 泛化用例：部分 -1（unknown dim）× {-2}（unknown rank），全部预期正向通过
    for (const auto& d : dtype_list) {
        for (const auto& c : dyn_list) {
            std::string case_name = d.name + "_" + c.name;
            printf("\n%s - INFO - [XIR]: ===== %s (dynamic graph desc) =====\n", GetTime().c_str(), case_name.c_str());
            CaseResult r = RunOneDynCase(session, graph_id, d.dt, c);
            results.push_back(r);
            graph_id++;
        }
    }

    PrintReport(results);

    bool all_pass = true;
    for (const auto& r : results) {
        bool pass = CasePassed(r);
        if (!pass) {
            all_pass = false;
        }
    }
    if (all_pass) {
        printf("\n%s - INFO - [XIR]: ALL CASES PASSED\n", GetTime().c_str());
    } else {
        printf("\n%s - ERROR - [XIR]: SOME CASES FAILED, see report above\n", GetTime().c_str());
    }

    delete session;
    printf("%s - INFO - [XIR]: Start to finalize ir graph session\n", GetTime().c_str());
    ret = ge::GEFinalize();
    if (ret != SUCCESS) {
        printf("%s - INFO - [XIR]: Finalize ir graph session failed\n", GetTime().c_str());
        return FAILED;
    }
    printf("%s - INFO - [XIR]: Finalize ir graph session success\n", GetTime().c_str());
    return all_pass ? SUCCESS : FAILED;
}
