def parse_str_to_shape_list(shape_str):
    shape_str = shape_str.strip("(").strip(")")
    shape_list = [int(x) for x in shape_str.split(",")]
    return np.array(shape_list)


def parse_bool_str(bool_str):
    return bool_str.strip().lower() == "true"


def gen_rois(x_shape, rois_num, spatial_scale, aligned, invalid_batch=False):
    """按列值域生成 rois (R,6) 行主序（SE 数据生成约束）:
    batch_idx ∈ [0,N) 整数语义 float 存储; center_x/center_y 为原图坐标
    （乘 spatial_scale 后落在特征图内）; w/h 为原图尺度宽高(>0);
    angle ∈ [0,π) 弧度。!aligned 用例追加一行极小 ROI 覆盖 max(1,·) 路径。
    invalid_batch=True 时向行 0/1/2 注入越界 batch_idx（-1/N/N+0.5），
    复现 L0 随机数据（默认 [-2,2) 随机值截断为 -1/1）触发 kernel 越界读的场景。
    """
    n = int(x_shape[0])
    h = int(x_shape[2])
    w = int(x_shape[3])
    orig_h = h / spatial_scale
    orig_w = w / spatial_scale
    rois = np.zeros((rois_num, 6), dtype=np.float64)
    for r in range(rois_num):
        rois[r, 0] = np.random.randint(0, n)
        roi_w = np.random.uniform(0.15 * orig_w, 0.5 * orig_w)
        roi_h = np.random.uniform(0.15 * orig_h, 0.5 * orig_h)
        rois[r, 1] = np.random.uniform(roi_w / 2.0, orig_w - roi_w / 2.0)
        rois[r, 2] = np.random.uniform(roi_h / 2.0, orig_h - roi_h / 2.0)
        rois[r, 3] = roi_w
        rois[r, 4] = roi_h
        rois[r, 5] = np.random.uniform(0.0, np.pi)
    if rois_num > 0 and not aligned:
        rois[-1, 3] = 1.5
        rois[-1, 4] = 1.5
    if invalid_batch and rois_num > 0:
        # 越界 batch_idx 注入：行 0/1/2 截断取整后 -1 / N / N（N+0.5 向零截断）均落在 [0,N) 之外
        rois[0, 0] = -1.0
        rois[1, 0] = float(n)
        if rois_num > 2:
            rois[2, 0] = n + 0.5
    return rois.astype(np.float32)


def bilinear_interpolate_nchw(feat, h, w, sy, sx):
    """NCHW 双线性插值（mmcv 边界语义三件套）:
    ① 越界 sy<-1|sy>H|sx<-1|sx>W 贡献 0; ② 负坐标 clamp 到 0;
    ③ floor >= size-1 时单点采样。feat: (C,H,W)，返回 (C,) 贡献值。
    """
    if sy < -1.0 or sy > h or sx < -1.0 or sx > w:
        return np.zeros(feat.shape[0], dtype=np.float64)
    if sy < 0.0:
        sy = 0.0
    if sx < 0.0:
        sx = 0.0
    y_low = int(sy)
    x_low = int(sx)
    if y_low >= h - 1:
        y_low = h - 1
        y_high = y_low
        sy = float(y_low)
    else:
        y_high = y_low + 1
    if x_low >= w - 1:
        x_low = w - 1
        x_high = x_low
        sx = float(x_low)
    else:
        x_high = x_low + 1
    ly = sy - y_low
    lx = sx - x_low
    hy = 1.0 - ly
    hx = 1.0 - lx
    v1 = feat[:, y_low, x_low]
    v2 = feat[:, y_low, x_high]
    v3 = feat[:, y_high, x_low]
    v4 = feat[:, y_high, x_high]
    return (hy * hx) * v1 + (hy * lx) * v2 + (ly * hx) * v3 + (ly * lx) * v4


def golden_roi_align_rotated(
    x, rois, pooled_h, pooled_w, spatial_scale, sampling_ratio, aligned, clockwise
):
    """mmcv roi_align_rotated 前向 golden（CPU fp64 锚，输出舍入 float32）。
    数学语义与 mmcv CUDA forward / 竞品一致：
    1. 先缩放后偏移禁止取整; theta = clockwise ? -angle : angle; !aligned 时 max(roi,1)
    2. bin_size = roi/pooled; grid = sampling_ratio>0 ? sampling_ratio : ceil(bin_size); count = max(grid_h*grid_w,1)
    3. 采样点 yy/xx → 旋转平移到特征图坐标 sy/sx
    4. NCHW 双线性插值求和后除以 count
    """
    n, c, h, w = x.shape
    r_num = int(rois.shape[0])
    golden = np.zeros((r_num, c, pooled_h, pooled_w), dtype=np.float64)
    if r_num == 0:
        return golden.astype(np.float32)
    x64 = x.astype(np.float64)
    rois64 = rois.astype(np.float64)
    offset = 0.5 if aligned else 0.0
    for r in range(r_num):
        batch_idx = int(rois64[r, 0])
        # 越界 batch_idx：该 ROI 不对应任何特征图平面，输出 0（与 kernel 越界防护语义一致）
        if batch_idx < 0 or batch_idx >= n:
            continue
        center_w = float(rois64[r, 1]) * spatial_scale - offset
        center_h = float(rois64[r, 2]) * spatial_scale - offset
        roi_w = float(rois64[r, 3]) * spatial_scale
        roi_h = float(rois64[r, 4]) * spatial_scale
        theta = -float(rois64[r, 5]) if clockwise else float(rois64[r, 5])
        if not aligned:
            roi_w = max(roi_w, 1.0)
            roi_h = max(roi_h, 1.0)
        bin_size_h = roi_h / pooled_h
        bin_size_w = roi_w / pooled_w
        grid_h = sampling_ratio if sampling_ratio > 0 else int(math.ceil(bin_size_h))
        grid_w = sampling_ratio if sampling_ratio > 0 else int(math.ceil(bin_size_w))
        count = max(grid_h * grid_w, 1)
        cos_t = math.cos(theta)
        sin_t = math.sin(theta)
        roi_start_h = -roi_h / 2.0
        roi_start_w = -roi_w / 2.0
        feat = x64[batch_idx]
        for ph in range(pooled_h):
            for pw in range(pooled_w):
                acc = np.zeros(c, dtype=np.float64)
                for iy in range(grid_h):
                    yy = (
                        roi_start_h + ph * bin_size_h + (iy + 0.5) * bin_size_h / grid_h
                    )
                    for ix in range(grid_w):
                        xx = (
                            roi_start_w
                            + pw * bin_size_w
                            + (ix + 0.5) * bin_size_w / grid_w
                        )
                        sy = yy * cos_t - xx * sin_t + center_h
                        sx = yy * sin_t + xx * cos_t + center_w
                        acc += bilinear_interpolate_nchw(feat, h, w, sy, sx)
                golden[r, :, ph, pw] = acc / count
    return golden.astype(np.float32)


