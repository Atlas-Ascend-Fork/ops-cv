"""Golden for resize_grad, pure torch implementation.

The cubic backward is the exact transpose of the bicubic forward: each output
(grad-input) point gathers a window of contributing grad positions, weighted by
the clamped-cubic basis. Two accumulation strategies share the identical math
(only the floating-point accumulation order differs):

* ``ResizeGradTestSpec.golden`` uses ``acc_mode="gather"`` so the reference
  follows the device's per-output gather order and does not overflow an
  intermediate tensor for inputs near the float32 upper bound.

* ``acc_mode="scatter"`` (allocation default; kept for independent cross-checks): a separable 2D
  scatter-add implemented with two ``index_add_`` passes (H then W). Each grad
  position scatters its contribution to its 4 clamped output neighbours.

* ``acc_mode="gather"`` (third-party / NPU-aligned): a separable 2D
  gather-add. Dense per-axis weight matrices are assembled first, then the
  inner W-gather accumulates ``ow`` ascending and the outer H-gather
  accumulates ``oh`` ascending. This mirrors the NPU kernel's per-output gather
  traversal (``for oh: for ow:``), so the float32 accumulation order matches the
  device result and the cross-check residual collapses to ~0.

The linear branch is unaffected and always uses its scalar scatter-add loop.
"""

