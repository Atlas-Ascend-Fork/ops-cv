    hwnc = data_format == "HWNC"
    g = grads.permute(2, 3, 0, 1).contiguous() if (hwnc and mode == "cubic") else grads
    n, c = int(g.shape[0]), int(g.shape[1])
    acc_dtype = torch.float32 if g.dtype in (torch.float16, torch.bfloat16) else g.dtype

    if mode == "cubic":
        assert len(original_size) == 4, "cubic mode requires 4-element original_size"
