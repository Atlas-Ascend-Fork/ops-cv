def _src_idx(scale, dst, align_corners, clamp_neg):
    """Source coordinate for output position ``dst``.

    Supports either a scalar (Python int/float, returns a Python float) or a
    1-D tensor of output positions (returns a float64 tensor). The scalar path
    is byte-for-byte identical to the original loop implementation so the
    ``linear`` branch (which only ever passes scalars) is unaffected.
    """
    if torch.is_tensor(dst):
        d = dst.to(torch.float64)
        if align_corners:
            v = scale * d
        else:
            v = scale * (d + 0.5) - 0.5
        if clamp_neg:
            v = torch.clamp(v, min=0.0)
        return v
    if align_corners:
        return scale * float(dst)
    v = scale * (float(dst) + 0.5) - 0.5
    return max(v, 0.0) if clamp_neg else v


