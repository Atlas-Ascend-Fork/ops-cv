class Dilation2DBackpropFilterDeterministicTiling : public testing::Test {
protected:
    struct Case {
        gert::Shape x;
        gert::Shape filter;
        gert::Shape gradient;
        std::string padding = "VALID";
        std::string format = "NHWC";
        std::vector<int64_t> strides = {1, 1, 1, 1};
        std::vector<int64_t> rates = {1, 1, 1, 1};
        std::vector<int64_t> pads = {0, 0, 0, 0};
    };

    struct Result {
        Dilation2DBackpropFilterTilingData data{};
        size_t workspace = 0;
        uint32_t blocks = 0;
    };

    static constexpr size_t SYSTEM_WORKSPACE = 16777216;

    // Build the actual registered host context; shape-only UTs allocate no tensor data.
    void Execute(const Case& c, Result& result)
    {
        const gert::StorageFormat format(ge::FORMAT_ND, ge::FORMAT_ND, gert::ExpandDimsType());
        const auto storage = [](const gert::Shape& shape) {
            gert::StorageShape result;
            result.MutableOriginShape() = shape;
            result.MutableStorageShape() = shape;
            return result;
        };
        gert::Tensor x(storage(c.x), format, gert::TensorPlacement::kOnHost, ge::DT_FLOAT, nullptr);
        gert::Tensor filter(storage(c.filter), format, gert::TensorPlacement::kOnHost, ge::DT_FLOAT, nullptr);
        gert::Tensor gradient(storage(c.gradient), format, gert::TensorPlacement::kOnHost, ge::DT_FLOAT, nullptr);
        gert::Tensor output(storage(c.filter), format, gert::TensorPlacement::kOnHost, ge::DT_FLOAT, nullptr);
        fe::PlatFormInfos platform;
        platform.Init();
        auto data = gert::TilingData::CreateCap(4096);
        auto workspace = gert::ContinuousVector::Create<size_t>(1);
        struct CompileInfo {
        } compileInfo;
        int32_t deterministic = 1;
        gert::TilingContextFaker builder;
        builder.SetOpType("Dilation2DBackpropFilter")
            .NodeIoNum(3, 1)
            .InputTensors({&x, &filter, &gradient})
            .OutputTensors({&output})
            .Attr("strides", c.strides)
            .Attr("rates", c.rates)
            .Attr("padding_mode", ge::AscendString(c.padding.c_str()))
            .Attr("pads", c.pads)
            .Attr("ceil_mode", false)
            .Attr("data_format", ge::AscendString(c.format.c_str()))
            .CompileInfo(&compileInfo)
            .PlatformInfo(&platform)
            .DeterministicInfo(&deterministic)
            .TilingData(data.get())
            .Workspace(reinterpret_cast<gert::ContinuousVector*>(workspace.get()));
        auto holder = builder.Build();
        auto* context = holder.GetContext();
        ASSERT_NE(context, nullptr);
        std::map<std::string, std::string> soc = {
            {"ai_core_cnt", "64"}, {"vector_core_cnt", "64"}, {"cube_core_cnt", "32"}, {"core_type_list", "AICore"}};
        std::map<std::string, std::string> core = {{"ub_size", "262144"}};
        std::map<std::string, std::string> version = {{"NpuArch", "3510"}, {"Short_SoC_version", "Ascend950"}};
        platform.SetPlatformRes("SoCInfo", soc);
        platform.SetPlatformRes("AICoreSpec", core);
        platform.SetPlatformRes("version", version);
        platform.SetCoreNumByCoreType("AICore");
        auto registry = gert::DefaultOpImplSpaceRegistryV2::GetInstance().GetSpaceRegistry();
        ASSERT_NE(registry, nullptr);
        auto impl = registry->GetOpImpl("Dilation2DBackpropFilter");
        ASSERT_NE(impl, nullptr);
        ASSERT_EQ(impl->tiling(context), ge::GRAPH_SUCCESS);
        EXPECT_EQ(context->GetTilingKey(), 0U);
        ASSERT_EQ(context->GetRawTilingData()->GetDataSize(), sizeof(result.data));
        std::memcpy(&result.data, context->GetRawTilingData()->GetData(), sizeof(result.data));
        result.blocks = context->GetBlockDim();
        ASSERT_NE(context->GetWorkspaceSizes(1), nullptr);
        result.workspace = context->GetWorkspaceSizes(1)[0];
        EXPECT_EQ(result.data.needCoreNum, result.blocks);
    }
};

TEST_F(Dilation2DBackpropFilterDeterministicTiling, channel_exclusive_workspace)
{
    Result r;
    ASSERT_NO_FATAL_FAILURE(Execute({{1, 8, 8, 128}, {3, 3, 128}, {1, 6, 6, 128}}, r));
    EXPECT_EQ(r.blocks, 64U);
    EXPECT_EQ(r.data.routeDense, 0);
    EXPECT_EQ(r.data.routeDenseScatter, 0);
    EXPECT_EQ(r.data.groupNum, 36);
    EXPECT_EQ(r.data.scratchStride, 16);
    EXPECT_EQ(r.data.routeBalancedMerge, 1);
    EXPECT_EQ(r.data.routeIndex32, 1);
    EXPECT_EQ(r.workspace, SYSTEM_WORKSPACE + 36U * 128 * 16 * sizeof(float));
}

