/*!
 * \file grid_unnormal_def.cpp
 * \brief GridUnnormal 算子定义（2 输入 grid/assist, 2 输出 diff/position, align_corners Bool 属性）
 *
 * dtype 表（2 行，按列对位）：grid/assist/diff = {fp16, fp32}，position = {int32, int32}。
 */
#include "register/op_def_registry.h"

namespace ops {
class GridUnnormal : public OpDef {
public:
    explicit GridUnnormal(const char* name) : OpDef(name)
    {
        this->Input("grid")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_FLOAT})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND, ge::FORMAT_ND});
        this->Input("assist")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_FLOAT})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND, ge::FORMAT_ND});
        this->Output("diff")
            .ParamType(REQUIRED)
            .DataType({ge::DT_FLOAT16, ge::DT_FLOAT})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND, ge::FORMAT_ND});
        this->Output("position")
            .ParamType(REQUIRED)
            .DataType({ge::DT_INT32, ge::DT_INT32})
            .Format({ge::FORMAT_ND, ge::FORMAT_ND})
            .UnknownShapeFormat({ge::FORMAT_ND, ge::FORMAT_ND});
        this->Attr("align_corners").AttrType(OPTIONAL).Bool(false);

        OpAICoreConfig aiCoreConfig;
        aiCoreConfig.DynamicCompileStaticFlag(true)
            .DynamicFormatFlag(false)
            .DynamicRankSupportFlag(true)
            .DynamicShapeSupportFlag(true)
            .NeedCheckSupportFlag(false)
            .PrecisionReduceFlag(false)
            .ExtendCfgInfo("opFile.value", "grid_unnormal");
        this->AICore().AddConfig("ascend950", aiCoreConfig);
        this->AICore().AddConfig("ascend350", aiCoreConfig);
    }
};
OP_ADD(GridUnnormal);
} // namespace ops
