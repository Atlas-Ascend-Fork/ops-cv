def _channels_last_from_geometry(t, out_spatial, scales):
    """Decide the layout when the request carries no format metadata.

    The aclnn XPU payload transports only tensors, attributes and the C-header
    parameter order (ttk aclnn worker ``_aclnn_xpu_derived``), so a third_party
    provider never sees ``tensor_formats``. An explicitly supplied scale still
    pins the layout down: only one reading of the view satisfies
    ``out == int(in * scale)`` on every axis. Falls back to channels-first (the
    aclnn declaration order) whenever the geometry does not single out exactly
    one reading - with default scales the two readings are indistinguishable
    here, so a channels-last case would have to declare the layout itself.
    """
