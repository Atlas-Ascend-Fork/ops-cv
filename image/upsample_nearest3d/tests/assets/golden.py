# ---------------------------------------------------------------------------
# Torch E2E (framework-api) layer
# ---------------------------------------------------------------------------
# The E2E container contract differs from both other modes, so this is an
# independent wrapper rather than an alias of the ACLNN entry:
#
#   * kernel mode -> numpy.ndarray, ``output_size`` legally EMPTY (the extent
#                    is then read off ``output_ori_shapes``), ``input_formats``
#   * ACLNN mode  -> torch.Tensor, scales as plain doubles with 0.0 meaning
#                    "unset", ``tensor_formats``
#   * E2E mode    -> CPU torch.Tensor passed POSITIONALLY in aten schema
#                    order, ``output_size`` always 3 elements, scales as
#                    Optional[float] with None meaning "unset", plus the fixed
#                    kwargs ``backend``/``tensor_formats``/``tensor_dtypes``/
#                    ``use_torch``/``short_soc_version``/``testcase_name``
#
# The reference does NOT forward to the CPU op of the same name. Besides
# making the test self-validating, that path carries ATen's ``nearest_idx``
# short-circuits (``out == in`` -> identity, ``out == 2*in`` -> ``index >> 1``),
# both of which discard an explicit ``scales`` argument while the device always
# applies the Ascend rule. The 3D entry only reaches the fast path when all
# three axes short-circuit, so the divergence is rarer here than in 2D - but
# it is the same defect, and TTK's third-level fallback (same API on CPU) would
# hit it. The index map is therefore built directly from the Ascend rule
# ``floor(dst * in/out)`` (or ``floor(dst / scale)`` when a scale is given),
# clamped to ``in - 1``, and applied per axis with ``index_select``.


def _e2e_axis_gather_3d(t, axis, out_len, scale):
    """Nearest gather along one axis using the Ascend index rule directly."""
    in_len = int(t.shape[axis])
    out_len = int(out_len)
    if scale is not None and scale > 0:
        s = torch.tensor(1.0, dtype=torch.float32) / torch.tensor(
            float(scale), dtype=torch.float32
        )
    else:
        s = torch.tensor(float(in_len), dtype=torch.float32) / torch.tensor(
            float(out_len), dtype=torch.float32
        )
    dst = torch.arange(out_len, dtype=torch.float32)
    idx = torch.clamp(torch.floor(dst * s).long(), max=in_len - 1)
    return t.index_select(axis, idx)


class TorchUpsampleNearest3dE2ETestSpec:
    """``torch.ops.aten.upsample_nearest3d(self, output_size, scales_d, scales_h, scales_w)``

    Eager dispatch measured with ``torch_npu.profiler``:
    aclnnUpsampleNearest3d -> **UpsampleNearest3d** (the delivered kernel).

    Coordinate semantic: Ascend ``(align_corners=False,
    half_pixel_centers=False)``. The alternatives have no usable framework
    entry on this operator - ``align_corners`` is rejected by every PyTorch
    nearest mode, and ``_upsample_nearest_exact3d`` dispatches to
    UpsampleNearestExact3d, a DIFFERENT operator - so neither is registered.
    The 3D BACKWARD entry (``upsample_nearest3d_backward``) likewise lands on
    UpsampleNearest3dGrad and is not registered.

    Unlike the 2D entries, all five dtypes stay on this operator: per-dtype
    profiling shows fp16/fp32/bf16/fp64/uint8 all dispatching to
    UpsampleNearest3dNcdhw, so the declaration below is wider here. That is a
    measured difference between the two operators, not a relaxation.
    """

    def golden(x, output_size, scales_d=None, scales_h=None, scales_w=None, **kwargs):
        t = x.detach().cpu()
        if t.dim() != 5:
            raise ValueError(
                f"aten::upsample_nearest3d expects a 5-D NCDHW input, got "
                f"{tuple(t.shape)}"
            )
        out_spatial = [int(v) for v in output_size]
