def _tp_axis_index(
    out_len, in_len, align_corners, half_pixel_centers, scale_attr, device
):
    """Nearest source index per output position, from torch primitives.

    Used by the third_party implementation for the legal combinations the
    public ``F.interpolate`` API cannot express. Among the delivered cases that
    is ``align_corners`` only - F.interpolate's nearest modes carry no
    align_corners - so rather than dropping those cases or substituting a
    different coordinate semantic, the index is built from verified torch ops
    (checked against the kernel rule, notes/verify_tp.py).

    The ``scale_attr`` branch is kept because the IR attribute and the aten
    schemas both admit the argument, not because any delivered case supplies
    it: every case leaves the attribute at its default, so callers always pass
    ``None`` here and the shape-derived ratio is used. (Historically that
    branch also covered explicit scales, which ``F.interpolate(scale_factor=
    ...)`` cannot represent at all because it derives the output length itself
    as floor(in*scale); that configuration is outside the delivered domain and
    is retained only as locating evidence.)
    """
    out_len = int(out_len)
    in_len = int(in_len)
    dst = torch.arange(out_len, dtype=torch.float32, device=device)
    if align_corners:
        ratio = (in_len - 1) / (out_len - 1) if out_len > 1 else 0.0
        coord = dst.to(torch.float64) * torch.tensor(
            ratio, dtype=torch.float64, device=device
        )
        # roundf == round-half-away-from-zero; coord >= 0 so floor(v+0.5) is it
        idx = torch.floor(coord + 0.5).long()
    else:
        if scale_attr is not None and scale_attr > 0:
            scale = torch.tensor(
                1.0, dtype=torch.float32, device=device
            ) / torch.tensor(float(scale_attr), dtype=torch.float32, device=device)
        else:
            scale = torch.tensor(
                float(in_len), dtype=torch.float32, device=device
            ) / torch.tensor(float(out_len), dtype=torch.float32, device=device)
        coord = (dst + 0.5) * scale if half_pixel_centers else dst * scale
        idx = torch.floor(coord).long()
    return torch.clamp(idx, max=in_len - 1)


def _tp_nearest_2d(x_nchw, out_hw, align_corners, half_pixel_centers, scales, device):
    """third_party 2D nearest: public F.interpolate when it can express the
    case, verified torch primitives otherwise. Runs on ``device``."""
    import torch.nn.functional as F

    s_h, s_w = scales
    explicit = s_h is not None or s_w is not None
    if not align_corners and not explicit:
        mode = "nearest-exact" if half_pixel_centers else "nearest"
        return F.interpolate(x_nchw, size=(int(out_hw[0]), int(out_hw[1])), mode=mode)
    ih = _tp_axis_index(
        out_hw[0], x_nchw.shape[-2], align_corners, half_pixel_centers, s_h, device
    )
    iw = _tp_axis_index(
        out_hw[1], x_nchw.shape[-1], align_corners, half_pixel_centers, s_w, device
    )
    return x_nchw.index_select(-2, ih).index_select(-1, iw)


