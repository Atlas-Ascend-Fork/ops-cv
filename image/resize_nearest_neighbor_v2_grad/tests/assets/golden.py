def _round_grads_inplace(g):
    """Round an upstream gradient in place and normalize negative zeros.

    Used by the integer case family: with |value| <= 8 and bounded collision
    counts the accumulated sums stay exactly representable in fp16/bf16/fp32,
    so any accumulation order is bit-exact. ``+ 0.0`` turns -0.0 into +0.0
    because the sign of a zero SUM is not part of the op contract (torch CPU
    yields +0.0 from ``0 + (-0.0)`` while the device ViewCopy path yields
    -0.0: numerically equal, bitwise different). Only the test data is
    normalized; index and accumulation semantics are still exercised by the
    non-zero values, and signed-zero pass-through is covered bitwise by the
    forward goldens.
    """
    if torch.is_tensor(g):
        if g.dim() > 0 and g.numel() > 0:
            g.round_()
            g.add_(0.0)
        return
    if isinstance(g, np.ndarray) and g.ndim > 0 and g.size > 0:
        if str(g.dtype) == "bfloat16":
            tmp = np.round(g.astype(np.float32)) + np.float32(0.0)
            g[...] = tmp.astype(g.dtype)
        else:
            np.round(g, out=g)
            g += g.dtype.type(0.0)


