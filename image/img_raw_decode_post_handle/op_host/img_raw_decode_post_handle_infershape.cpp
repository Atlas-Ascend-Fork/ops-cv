static constexpr int64_t IDX_0 = 0;
static constexpr int64_t IDX_1 = 1;
static constexpr int64_t IDX_4 = 4; // img_size 输入索引
static constexpr int64_t IDX_5 = 5; // gamma 输入索引
static constexpr int64_t NUM_4 = 4; // 通道输入数量
static constexpr int64_t RANK_2 = 2;
static constexpr int64_t RANK_1 = 1;
static constexpr int64_t IMG_SIZE_ELEM_NUM = 2;
static constexpr size_t IMG_SIZE_BYTES = static_cast<size_t>(IMG_SIZE_ELEM_NUM) * sizeof(int32_t);
