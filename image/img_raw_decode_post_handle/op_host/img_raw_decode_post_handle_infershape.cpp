// 推导输出 shape（值依赖 img_size）：
//   img_size 值不可获取（动态 shape）→ 输出设为 (-1, -1)；否则输出设为 (h_out, w_out)
static ge::graphStatus InferOutputShape(gert::InferShapeContext* context)
{
    gert::Shape* outputShape = context->GetOutputShape(IDX_0);
    OP_CHECK_NULL_WITH_CONTEXT(context, outputShape);

    const auto* imgSizeTensor = context->GetInputTensor(IDX_4);
    if (imgSizeTensor == nullptr) {
        outputShape->SetDimNum(RANK_2);
        outputShape->SetDim(IDX_0, UNKNOWN_DIM);
        outputShape->SetDim(IDX_1, UNKNOWN_DIM);
        OP_LOGD(context->GetNodeName(), "img_size tensor null, set output to (-1, -1)");
        return GRAPH_SUCCESS;
    }

    // 图模式 Data 输入在 infershape 阶段只有 shape、没有运行期数据，数据指针为空；
    // 此时按“值不可获取”处理，输出设为 (-1, -1)。
    // 注意不能用 GetSize()==0 判断：img_size 为未知 shape（dim0==-1）但带 const 值时
    // GetSize() 同样为 0，会误判为无数据。
    const int32_t* imgSizeData = imgSizeTensor->GetData<int32_t>();
    if (imgSizeData == nullptr) {
        outputShape->SetDimNum(RANK_2);
        outputShape->SetDim(IDX_0, UNKNOWN_DIM);
        outputShape->SetDim(IDX_1, UNKNOWN_DIM);
        OP_LOGD(context->GetNodeName(), "img_size data unavailable, set output to (-1, -1)");
        return GRAPH_SUCCESS;
    }

    // shape 声明了具体元素个数时，数据不足 2 个 int32 则拒绝，避免越界读；
    // dim0 为未知维（-1）时 GetSize() 为 0，无法据此判断，直接按值读取。
    const gert::Shape* imgSizeShape = context->GetInputShape(IDX_4);
    int64_t imgSizeDim0 = (imgSizeShape == nullptr) ? UNKNOWN_DIM : imgSizeShape->GetDim(IDX_0);
    if (imgSizeDim0 != UNKNOWN_DIM && imgSizeTensor->GetSize() < IMG_SIZE_BYTES) {
        OP_LOGE_WITH_INVALID_INPUT_SHAPESIZE(context->GetNodeName(), IDX_4,
                                             std::to_string(imgSizeTensor->GetSize() / sizeof(int32_t)).c_str(),
                                             std::to_string(IMG_SIZE_ELEM_NUM).c_str());
        return GRAPH_FAILED;
    }
    int64_t hOut = static_cast<int64_t>(imgSizeData[IDX_0]);
    int64_t wOut = static_cast<int64_t>(imgSizeData[IDX_1]);
    if (hOut <= 0 || wOut <= 0) {
        OP_LOGE_FOR_INVALID_SHAPE_WITH_REASON(context->GetNodeName(), "img_size",
                                              ("[" + std::to_string(hOut) + ", " + std::to_string(wOut) + "]").c_str(),
                                              "img_size values must be positive");
        return GRAPH_FAILED;
    }
    outputShape->SetDimNum(RANK_2);
    outputShape->SetDim(IDX_0, hOut);
    outputShape->SetDim(IDX_1, wOut);
    OP_LOGD(context->GetNodeName(), "Output shape: (%ld, %ld)", hOut, wOut);
    return GRAPH_SUCCESS;
}

static ge::graphStatus InferShapeImgRawDecodePostHandle(gert::InferShapeContext* context)
{
    OP_LOGD(context->GetNodeName(), "Begin InferShapeImgRawDecodePostHandle");

    // 1. 任一输入为 unknown rank → 跳过所有校验，输出设为 unknown rank
    if (IsAnyInputUnknownRank(context)) {
        gert::Shape* outputShape = context->GetOutputShape(IDX_0);
        OP_CHECK_NULL_WITH_CONTEXT(context, outputShape);
        Ops::Base::SetUnknownRank(*outputShape);
        OP_LOGD(context->GetNodeName(), "Input unknown rank, set output to unknown rank");
        return GRAPH_SUCCESS;
    }

    // 2. 非 unknown rank 时校验输入，unknown dim -1 视为通配，不报错
    graphStatus ret = ValidateChannelShapes(context);
    if (ret != GRAPH_SUCCESS) {
        return ret;
    }
    ret = ValidateImgSizeShape(context);
    if (ret != GRAPH_SUCCESS) {
        return ret;
    }
    ret = ValidateGammaShape(context);
    if (ret != GRAPH_SUCCESS) {
        return ret;
    }

    // 3. 推导输出 shape（值依赖 img_size）
    return InferOutputShape(context);
}

