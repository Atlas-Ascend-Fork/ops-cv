    float v1 = static_cast<float>(lutTable[idx1 * 3 + c]);
    float v2 = static_cast<float>(lutTable[idx2 * 3 + c]);
    float v3 = static_cast<float>(lutTable[idx3 * 3 + c]);
    float v4 = static_cast<float>(lutTable[idx4 * 3 + c]);
    float v5 = static_cast<float>(lutTable[idx5 * 3 + c]);
    float v6 = static_cast<float>(lutTable[idx6 * 3 + c]);
    float v7 = static_cast<float>(lutTable[idx7 * 3 + c]);

    // R axis: 8 -> 4
    float vr0 = v0 * fractR1 + v4 * fractR;
    float vr1 = v1 * fractR1 + v5 * fractR;
    float vr2 = v2 * fractR1 + v6 * fractR;
    float vr3 = v3 * fractR1 + v7 * fractR;
