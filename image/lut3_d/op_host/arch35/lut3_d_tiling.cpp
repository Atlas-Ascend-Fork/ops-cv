static ge::graphStatus ValidateShapes(gert::TilingContext* context, int64_t& totalPixels, int64_t& lutN)
{
    auto imgInput = context->GetInputShape(0);
    OP_CHECK_NULL_WITH_CONTEXT(context, imgInput);
    auto imgShape = imgInput->GetStorageShape();
    auto lutInput = context->GetInputShape(1);
    OP_CHECK_NULL_WITH_CONTEXT(context, lutInput);
    auto lutShape = lutInput->GetStorageShape();

    int64_t imgDimNum = static_cast<int64_t>(imgShape.GetDimNum());
    if (imgDimNum != 3 && imgDimNum != 4) {
        OP_LOGE_FOR_INVALID_SHAPEDIM(context->GetNodeName(), "img", std::to_string(imgDimNum).c_str(), "3 or 4");
        return ge::GRAPH_FAILED;
    }
    for (int64_t i = 0; i < imgDimNum; ++i) {
        const int64_t imgDim = imgShape.GetDim(i);
        if (imgDim < 0 && imgDim != ge::UNKNOWN_DIM) {
            OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "img dimension",
                                                  std::to_string(imgDim).c_str(),
                                                  "must be non-negative or UNKNOWN_DIM");
            return ge::GRAPH_FAILED;
        }
    }
    if (imgShape.GetDim(imgDimNum - 1) != 3) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "img last dim",
                                              std::to_string(imgShape.GetDim(imgDimNum - 1)).c_str(),
                                              "img last dim must be 3");
        return ge::GRAPH_FAILED;
    }

    if (lutShape.GetDimNum() != 4) {
        OP_LOGE_FOR_INVALID_SHAPEDIM(context->GetNodeName(), "lut_table", std::to_string(lutShape.GetDimNum()).c_str(),
                                     "4");
        return ge::GRAPH_FAILED;
    }
    if (lutShape.GetDim(3) != 3) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "lut_table dim[3]",
                                              std::to_string(lutShape.GetDim(3)).c_str(), "must be 3");
        return ge::GRAPH_FAILED;
    }
    if (lutShape.GetDim(0) != lutShape.GetDim(1) || lutShape.GetDim(1) != lutShape.GetDim(2)) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(
            context->GetNodeName(), "lut_table dims",
            ("dim[0]=" + std::to_string(lutShape.GetDim(0)) + ", dim[1]=" + std::to_string(lutShape.GetDim(1)) +
             ", dim[2]=" + std::to_string(lutShape.GetDim(2)))
                .c_str(),
            "dim[0], dim[1], dim[2] must be equal");
        return ge::GRAPH_FAILED;
    }
    lutN = lutShape.GetDim(0);
    if (lutN < 1) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "lut_table dim[0]", std::to_string(lutN).c_str(),
                                              "must not be less than 1");
        return ge::GRAPH_FAILED;
    }
    if (lutN > 20) {
        OP_LOGE_FOR_INVALID_VALUE_WITH_REASON(context->GetNodeName(), "lut_table dim[0]", std::to_string(lutN).c_str(),
                                              "must not be greater than 20");
        return ge::GRAPH_FAILED;
    }

    totalPixels = imgShape.GetShapeSize() / 3;
    return ge::GRAPH_SUCCESS;
}

